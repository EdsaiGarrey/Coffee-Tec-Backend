package mx.coffeetec.pojo;

import java.time.OffsetDateTime;

/** POJO de la tabla public.usuario. */
public class Usuario {

    private Long idUsuario;
    private Long idEmpleado;
    private Short idRol;
    private String nombreUsuario;
    private String correo;
    // Solo almacenar hashes; nunca contrasenas en texto plano.
    private String contrasenaHash;
    private Boolean activo;
    private Boolean debeCambiarClave;
    private OffsetDateTime fechaCreacion;
    private OffsetDateTime ultimoAcceso;

    public Usuario() {
    }

    public Long getIdUsuario() {
        return idUsuario;
    }

    public void setIdUsuario(Long idUsuario) {
        this.idUsuario = idUsuario;
    }

    public Long getIdEmpleado() {
        return idEmpleado;
    }

    public void setIdEmpleado(Long idEmpleado) {
        this.idEmpleado = idEmpleado;
    }

    public Short getIdRol() {
        return idRol;
    }

    public void setIdRol(Short idRol) {
        this.idRol = idRol;
    }

    public String getNombreUsuario() {
        return nombreUsuario;
    }

    public void setNombreUsuario(String nombreUsuario) {
        this.nombreUsuario = nombreUsuario;
    }

    public String getCorreo() {
        return correo;
    }

    public void setCorreo(String correo) {
        this.correo = correo;
    }

    public String getContrasenaHash() {
        return contrasenaHash;
    }

    public void setContrasenaHash(String contrasenaHash) {
        this.contrasenaHash = contrasenaHash;
    }

    public Boolean getActivo() {
        return activo;
    }

    public void setActivo(Boolean activo) {
        this.activo = activo;
    }

    public Boolean getDebeCambiarClave() {
        return debeCambiarClave;
    }

    public void setDebeCambiarClave(Boolean debeCambiarClave) {
        this.debeCambiarClave = debeCambiarClave;
    }

    public OffsetDateTime getFechaCreacion() {
        return fechaCreacion;
    }

    public void setFechaCreacion(OffsetDateTime fechaCreacion) {
        this.fechaCreacion = fechaCreacion;
    }

    public OffsetDateTime getUltimoAcceso() {
        return ultimoAcceso;
    }

    public void setUltimoAcceso(OffsetDateTime ultimoAcceso) {
        this.ultimoAcceso = ultimoAcceso;
    }

}
